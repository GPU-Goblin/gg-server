//! `cargo xtask`: local automation without shell scripts.

mod db;
mod demo;
mod release;
mod worker;

use clap::{Parser, Subcommand};

#[derive(Parser)]
#[command(name = "xtask", about = "GPU Goblin automation")]
struct Cli {
    #[command(subcommand)]
    cmd: Cmd,
}

#[derive(Subcommand)]
enum Cmd {
    /// PostgreSQL development database (docker, localhost only).
    Db {
        #[command(subcommand)]
        cmd: DbCmd,
    },
    /// fmt, clippy (-D warnings), tests (CPU + real PostgreSQL).
    Check,
    /// Reference demonstration: server, workers, validator, real tasks, receipts and ledger report.
    Demo(demo::DemoArgs),
    /// Build the distributed executables and sign a manifest of exactly what was built.
    Release(release::ReleaseArgs),
    /// Inventory of dependencies and licences of the whole workspace.
    Licenses {
        /// Write the inventory to this file instead of printing it.
        #[arg(long)]
        out: Option<std::path::PathBuf>,
    },
}

#[derive(Subcommand)]
enum DbCmd {
    /// Start (or create) the container.
    Up,
    /// Stop the container (data kept).
    Down,
    /// Destroy the container and its data, then start a fresh one.
    Reset,
    /// Print connection status.
    Status,
    /// Dump the database (custom format) and copy the server object store into a directory.
    Backup {
        /// Output directory.
        #[arg(long)]
        out: String,
        /// Server data directory (objects/, server.key); defaults to ./var/server.
        #[arg(long, default_value = "var/server")]
        data_dir: String,
    },
    /// Restore a backup directory (replaces the database content; requires --yes).
    Restore {
        /// Backup directory produced by `backup`.
        #[arg(long)]
        from: String,
        /// Server data directory to restore objects into.
        #[arg(long, default_value = "var/server")]
        data_dir: String,
        #[arg(long)]
        yes: bool,
    },
}

fn main() -> anyhow::Result<()> {
    let cli = Cli::parse();
    match cli.cmd {
        Cmd::Db { cmd } => match cmd {
            DbCmd::Up => db::up(),
            DbCmd::Down => db::down(),
            DbCmd::Reset => db::reset(),
            DbCmd::Status => db::status(),
            DbCmd::Backup { out, data_dir } => db::backup(&out, &data_dir),
            DbCmd::Restore {
                from,
                data_dir,
                yes,
            } => db::restore(&from, &data_dir, yes),
        },
        Cmd::Check => check(),
        Cmd::Demo(args) => demo::run(args),
        Cmd::Release(args) => release::run(args),
        Cmd::Licenses { out } => licenses(out.as_deref()),
    }
}

/// Inventory of every dependency actually compiled, with its licence. Read from `cargo metadata`,
/// so it describes the build rather than a hand-kept list.
fn licenses(out: Option<&std::path::Path>) -> anyhow::Result<()> {
    use std::collections::BTreeMap;

    let mut report = String::from("# Dependency and license inventory\n\n");
    report.push_str(
        "Generated by `cargo xtask licenses` from `cargo metadata`: this inventory describes the\n\
         packages actually compiled, not a hand-kept list.\n\n",
    );
    for (label, manifest) in [
        ("Main workspace", "Cargo.toml"),
        ("CosmWasm contract", "contracts/gg-rewards/Cargo.toml"),
    ] {
        let output = std::process::Command::new("cargo")
            .args([
                "metadata",
                "--format-version",
                "1",
                "--manifest-path",
                manifest,
            ])
            .output()?;
        anyhow::ensure!(
            output.status.success(),
            "cargo metadata failed for {manifest}"
        );
        let meta: serde_json::Value = serde_json::from_slice(&output.stdout)?;
        let packages = meta["packages"].as_array().cloned().unwrap_or_default();
        let mut by_licence: BTreeMap<String, Vec<String>> = BTreeMap::new();
        for p in &packages {
            let name = p["name"].as_str().unwrap_or("?").to_owned();
            let version = p["version"].as_str().unwrap_or("?").to_owned();
            let licence = p["license"]
                .as_str()
                .map(|s| s.to_owned())
                .or_else(|| p["license_file"].as_str().map(|f| format!("file: {f}")))
                .unwrap_or_else(|| "not declared".into());
            by_licence
                .entry(licence)
                .or_default()
                .push(format!("{name} {version}"));
        }
        report.push_str(&format!(
            "## {label} ({} packages)\n\n| License | Packages |\n|---|---|\n",
            packages.len()
        ));
        for (licence, mut names) in by_licence {
            names.sort();
            report.push_str(&format!(
                "| {licence} | {} |\n",
                names.join(", ").chars().take(1500).collect::<String>()
            ));
        }
        report.push('\n');
    }
    match out {
        Some(path) => {
            std::fs::write(path, &report)?;
            println!("inventory written to {}", path.display());
        }
        None => print!("{report}"),
    }
    Ok(())
}

fn run(cmd: &str, args: &[&str]) -> anyhow::Result<()> {
    let status = std::process::Command::new(cmd).args(args).status()?;
    anyhow::ensure!(
        status.success(),
        "{cmd} {} failed with {status}",
        args.join(" ")
    );
    Ok(())
}

/// Run a command inside `dir`. Cargo reads `.cargo/config.toml` from the working directory, not from
/// the manifest's directory, so the contract's wasm link flags only apply when we run there.
fn run_in(dir: &str, cmd: &str, args: &[&str]) -> anyhow::Result<()> {
    let status = std::process::Command::new(cmd)
        .args(args)
        .current_dir(dir)
        .status()?;
    anyhow::ensure!(
        status.success(),
        "{cmd} {} in {dir} failed with {status}",
        args.join(" ")
    );
    Ok(())
}

fn check() -> anyhow::Result<()> {
    db::ensure_env()?;
    run("cargo", &["fmt", "--all", "--check"])?;
    run(
        "cargo",
        &[
            "clippy",
            "--workspace",
            "--all-targets",
            "--",
            "-D",
            "warnings",
        ],
    )?;
    run("cargo", &["test", "--workspace"])?;
    contract_check()?;
    println!("check: ok");
    Ok(())
}

/// The reward contract is its own workspace (CosmWasm needs `panic = "abort"` for wasm32), so it is
/// checked explicitly: format, lints, native tests on a simulated chain, then the Wasm artifact and
/// its entry points.
fn contract_check() -> anyhow::Result<()> {
    let dir = "contracts/gg-rewards";
    run_in(dir, "cargo", &["fmt", "--check"])?;
    run_in(
        dir,
        "cargo",
        &["clippy", "--all-targets", "--", "-D", "warnings"],
    )?;
    run_in(dir, "cargo", &["test"])?;
    run_in(
        dir,
        "cargo",
        &[
            "build",
            "--target",
            "wasm32-unknown-unknown",
            "--release",
            "--lib",
        ],
    )?;
    let wasm = std::path::Path::new(
        "contracts/gg-rewards/target/wasm32-unknown-unknown/release/gg_rewards.wasm",
    );
    let bytes = std::fs::read(wasm)
        .map_err(|e| anyhow::anyhow!("no wasm artifact at {}: {e}", wasm.display()))?;
    anyhow::ensure!(
        bytes.starts_with(b"\0asm"),
        "the artifact is not a wasm module"
    );
    let exports = wasm_exports(&bytes)?;
    for entry in ["instantiate", "execute", "query", "allocate", "deallocate"] {
        anyhow::ensure!(
            exports.iter().any(|e| e == entry),
            "the contract does not export {entry}"
        );
    }
    anyhow::ensure!(
        exports.iter().any(|e| e.starts_with("interface_version_")),
        "the contract declares no CosmWasm interface version"
    );
    println!(
        "contract: ok ({} KiB, exports {})",
        bytes.len() / 1024,
        exports.join(", ")
    );
    Ok(())
}

/// Names exported by a wasm module, read from its export section.
fn wasm_exports(bytes: &[u8]) -> anyhow::Result<Vec<String>> {
    fn uleb(b: &[u8], i: &mut usize) -> anyhow::Result<u64> {
        let (mut result, mut shift) = (0u64, 0u32);
        loop {
            let byte = *b.get(*i).ok_or_else(|| anyhow::anyhow!("truncated wasm"))?;
            *i += 1;
            result |= u64::from(byte & 0x7f) << shift;
            if byte & 0x80 == 0 {
                return Ok(result);
            }
            shift += 7;
            anyhow::ensure!(shift < 64, "malformed wasm integer");
        }
    }
    let mut i = 8; // magic + version
    let mut exports = Vec::new();
    while i < bytes.len() {
        let id = bytes[i];
        i += 1;
        let size = uleb(bytes, &mut i)? as usize;
        let end = i + size;
        anyhow::ensure!(end <= bytes.len(), "truncated wasm section");
        if id == 7 {
            let mut j = i;
            let count = uleb(bytes, &mut j)?;
            for _ in 0..count {
                let len = uleb(bytes, &mut j)? as usize;
                let name = std::str::from_utf8(&bytes[j..j + len])?.to_owned();
                j += len + 1; // name + export kind
                let _ = uleb(bytes, &mut j)?;
                exports.push(name);
            }
        }
        i = end;
    }
    exports.retain(|e| !e.starts_with("__"));
    Ok(exports)
}
